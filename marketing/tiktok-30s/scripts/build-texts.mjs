// Bundles text.<lang>.json into src/texts.gen.js (the composition may not fetch
// at render time) and refuses to build when a string would break the brief:
// a character the pixel fonts cannot draw, or a promise the product does not keep.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const LANGS = ['ru', 'en', 'et']

/** Characters the engine draws itself as 7x7 icons (src/engine.js ICONS). */
const ICONS = new Set([...'✓●▲■○→'])

/** Code points covered by a font's cmap (formats 4 and 12). */
function cmap(file) {
  const b = readFileSync(file)
  const numTables = b.readUInt16BE(4)
  let off = -1
  for (let i = 0; i < numTables; i++) {
    const rec = 12 + i * 16
    if (b.toString('latin1', rec, rec + 4) === 'cmap') off = b.readUInt32BE(rec + 8)
  }
  if (off < 0) throw new Error('no cmap in ' + file)
  const set = new Set()
  const n = b.readUInt16BE(off + 2)
  for (let i = 0; i < n; i++) {
    const sub = off + b.readUInt32BE(off + 4 + i * 8 + 4)
    const format = b.readUInt16BE(sub)
    if (format === 4) {
      const segX2 = b.readUInt16BE(sub + 6)
      const ends = sub + 14
      const starts = ends + segX2 + 2
      const deltas = starts + segX2
      const ranges = deltas + segX2
      for (let s = 0; s < segX2; s += 2) {
        const end = b.readUInt16BE(ends + s)
        const start = b.readUInt16BE(starts + s)
        const delta = b.readInt16BE(deltas + s)
        const range = b.readUInt16BE(ranges + s)
        for (let c = start; c <= end && c !== 0xffff; c++) {
          let gid
          if (range === 0) gid = (c + delta) & 0xffff
          else {
            const at = ranges + s + range + (c - start) * 2
            gid = b.readUInt16BE(at)
            if (gid) gid = (gid + delta) & 0xffff
          }
          if (gid) set.add(c)
        }
      }
    } else if (format === 12) {
      const groups = b.readUInt32BE(sub + 12)
      for (let gi = 0; gi < groups; gi++) {
        const g = sub + 16 + gi * 12
        for (let c = b.readUInt32BE(g); c <= b.readUInt32BE(g + 4); c++) set.add(c)
      }
    }
  }
  return set
}

const fonts = {
  'Press Start 2P': cmap(join(root, 'assets/fonts/PressStart2P-Regular.ttf')),
  'Departure Mono': cmap(join(root, 'assets/fonts/DepartureMono-Regular.otf')),
}

// What the ad may not say (brief, "Что можно и нельзя обещать").
const BANNED = [
  /геолокац/i, /gps/i, /geoloc/i, /asukoh/i,
  /без выезда/i, /в фоне/i, /background/i, /taustal/i,
  /telegram/i, /телеграм/i, /\bsms\b/i, /смс/i,
  /(^|[^а-яё])ии([^а-яё]|$)/i, /\bai\b/i, /нейросет/i, /tehisintellekt/i,
  /реальн/i, /\breal\b/i, /real[- ]time/i, /reaalaja/i,
  /отзыв/i, /клиентов/i, /customers/i, /klienti/i,
]

const all = {}
const errors = []
const warnings = []
const keysOf = (o, p = '') =>
  Object.entries(o).flatMap(([k, v]) => (typeof v === 'object' ? keysOf(v, p + k + '.') : [p + k]))

for (const lang of LANGS) {
  const data = JSON.parse(readFileSync(join(root, `text.${lang}.json`), 'utf8'))
  all[lang] = data
  const walk = (o, path) => {
    for (const [k, v] of Object.entries(o)) {
      const p = path + k
      if (k === '_meta') continue
      if (typeof v === 'object') walk(v, p + '.')
      else {
        for (const ch of v) {
          if (ch === ' ' || ICONS.has(ch)) continue
          // buttons and role labels are upper-cased by the composition
          for (const variant of new Set([ch, ch.toLocaleUpperCase()])) {
            for (const [name, set] of Object.entries(fonts)) {
              for (const cp of variant) {
                if (!set.has(cp.codePointAt(0))) errors.push(`${lang}:${p} — "${cp}" is missing from ${name}`)
              }
            }
          }
        }
        for (const re of BANNED) if (re.test(v)) errors.push(`${lang}:${p} — banned wording ${re}: "${v}"`)
        if (v.includes('<<')) warnings.push(`${lang}:${p} is still a placeholder: ${v}`)
      }
    }
  }
  walk(data, '')
}

const base = keysOf(all.ru).filter((k) => !k.startsWith('_meta')).sort().join('|')
for (const lang of LANGS) {
  const mine = keysOf(all[lang]).filter((k) => !k.startsWith('_meta')).sort().join('|')
  if (mine !== base) errors.push(`${lang}: keys differ from text.ru.json`)
}

if (errors.length) {
  console.error('Text check failed:\n  ' + [...new Set(errors)].join('\n  '))
  process.exit(1)
}
for (const w of warnings) console.warn('warning: ' + w)

writeFileSync(
  join(root, 'src/texts.gen.js'),
  '// GENERATED by scripts/build-texts.mjs from text.<lang>.json. Do not edit.\n' +
    'window.AD_TEXTS = ' + JSON.stringify(all, null, 2) + '\n',
)
console.log(`texts: ${LANGS.join(', ')} ok, every character is in both fonts`)
